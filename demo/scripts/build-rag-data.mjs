import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const documentsDir = path.join(root, "rag", "documents");
const outputFile = path.join(root, "src", "rag-data.generated.js");
const kvSeedFile = path.join(root, "rag", "kv-seed.generated.json");
const maxChunkLength = 850;

const categoryByPrefix = {
  "01": "差旅标准",
  "02": "报销规定",
  "03": "预订指南",
  "04": "常见问题",
  "05": "应急指南",
  "06": "平台指南",
  "07": "城市指南",
  "08": "低碳出行",
};

function splitLongBlock(block) {
  if (block.length <= maxChunkLength) return [block];
  const lines = block.split("\n");
  const parts = [];
  let current = "";
  for (const line of lines) {
    if (current && current.length + line.length + 1 > maxChunkLength) {
      parts.push(current.trim());
      current = "";
    }
    current += `${current ? "\n" : ""}${line}`;
  }
  if (current.trim()) parts.push(current.trim());
  return parts;
}

function chunkDocument(text, title) {
  const blocks = text
    .replace(/\r\n/g, "\n")
    .split(/\n\s*\n/)
    .map((block) => block.trim())
    .filter(Boolean)
    .flatMap(splitLongBlock);
  const chunks = [];
  let current = "";
  for (const block of blocks) {
    const candidate = [current, block].filter(Boolean).join("\n\n");
    if (current && candidate.length > maxChunkLength) {
      chunks.push(current);
      current = `${title}\n\n${block}`;
    } else {
      current = candidate;
    }
  }
  if (current) chunks.push(current);
  return chunks;
}

const files = (await readdir(documentsDir)).filter((name) => name.endsWith(".txt")).sort();
const chunks = [];
const documents = [];

for (const file of files) {
  const text = await readFile(path.join(documentsDir, file), "utf8");
  const title = text.split(/\r?\n/).find((line) => line.trim())?.trim() || file;
  const category = categoryByPrefix[file.slice(0, 2)] || "差旅知识";
  const documentChunks = chunkDocument(text, title);
  documentChunks.forEach((content, index) => {
    chunks.push({
      id: `${file.slice(0, 2)}-${String(index + 1).padStart(3, "0")}`,
      title,
      category,
      file,
      chunk_index: index + 1,
      content,
    });
  });
  documents.push({
    id: `built-in-${file.slice(0, 2)}`,
    name: file,
    title,
    category,
    size: text.length,
    chunk_count: documentChunks.length,
    vector_ids: documentChunks.map((_, index) => `${file.slice(0, 2)}-${String(index + 1).padStart(3, "0")}`),
    content: text,
    built_in: true,
    created_at: "2026-08-05T00:00:00.000Z",
  });
}

const output = `// Generated by scripts/build-rag-data.mjs. Do not edit manually.\nexport const RAG_DOCUMENTS = ${JSON.stringify(chunks, null, 2)};\n`;
await writeFile(outputFile, output, "utf8");
await writeFile(kvSeedFile, JSON.stringify(documents.map((document) => ({
  key: `doc:${document.id}`,
  value: JSON.stringify(document),
})), null, 2), "utf8");
console.log(`Generated ${chunks.length} RAG chunks from ${files.length} documents.`);
